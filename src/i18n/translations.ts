export const getTranslation = (lang: Language, key: keyof typeof translations['ar']): string => {
  return translations[lang][key] || translations['ar'][key] || key;
};

export const formatCurrency = (amount: number, lang: Language): string => {
  const formatted = new Intl.NumberFormat(lang === 'ar' ? 'ar-MA' : 'fr-MA', {
    maximumFractionDigits: 0
  }).format(amount);

  return lang === 'ar' ? `${formatted} د.م.` : `${formatted} DH`;
};
